#!/usr/bin/env bash
# DearMe — build and deploy to /home/Debz/Host/dearme (https://dearme.koushikdeb.com).
# Caddy serves web/ and proxies /api/* to uvicorn on 127.0.0.1:8160 (block "# >>> dearme" in
# /home/Debz/Host/saarthi/Caddyfile). Safe to re-run: idempotent.
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${DEST:-/home/Debz/Host/dearme}"
DOMAIN="${DOMAIN:-dearme.koushikdeb.com}"
PORT="${PORT:-8160}"

echo "==> tests"
(cd "$SRC/backend" && .venv/bin/pytest -q)
(cd "$SRC/frontend" && npm test --silent)
python3 "$SRC/scripts/claim_lint.py"

echo "==> build frontend"
(cd "$SRC/frontend" && npm run build >/dev/null)

echo "==> sync to $DEST"
mkdir -p "$DEST"/{backend,web,seed,fixtures,logs,storage}
rsync -a --delete --exclude .venv --exclude __pycache__ --exclude .pytest_cache --exclude tests \
  "$SRC/backend/" "$DEST/backend/"
rsync -a --delete "$SRC/frontend/dist/" "$DEST/web/"
rsync -a --delete "$SRC/seed/" "$DEST/seed/"
rsync -a --delete --exclude private "$SRC/fixtures/" "$DEST/fixtures/"
cp "$SRC/scripts/host/run.sh" "$SRC/scripts/host/stop.sh" "$SRC/scripts/host/autostart.sh" "$DEST/"
chmod +x "$DEST"/{run,stop,autostart}.sh

echo "==> production .env (only the keys DearMe uses, plus prod overrides)"
python3 - "$SRC/.env" "$DEST/.env" "$DOMAIN" "$DEST" <<'PY'
import re, sys
src, dest, domain, root = sys.argv[1:]
keep = re.compile(r"^(YOUCAM_.*|YouCam_Phd_API_KEY|DEEPSEEK_API_KEY(_1|_2)?|DEEPSEEK_API_BASE_URL|DEEPSEEK_MODEL|"
                  r"KIMI_.*|KIMI_2009_API_KEY|NANOGPT_.*|NanoGPT_2009_API_KEY|LLM_.*|SARVAM_API_KEY|SARVAM_2009_API_KEY|"
                  r"Open_AI_2009_Key|OPENAI_API_KEY|STT_PROVIDER|TTS_ENABLED|"
                  r"INTEGRITY_SHARED_SECRET|SHARE_TOKEN_SECRET|STORE_DASHBOARD_PASSWORD|IMAGE_RETENTION_HOURS|"
                  r"DEFAULT_LOCALE|DATABASE_URL|DEMO_USER|DEMO_PASSWORD)$")
out = {}
for line in open(src, encoding="utf-8"):
    m = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$", line.rstrip("\n"))
    if m and keep.match(m.group(1)):
        out[m.group(1)] = m.group(2)
out["DATABASE_URL"] = re.sub(r"/[^/]+$", "/dearme", out["DATABASE_URL"])
out.update(APP_ENV="production", APP_URL=f"https://{domain}", MOCK_MODE="true", COOKIE_SECURE="true",
           STORAGE_DIR=f"{root}/storage", GEO_REVERSE_PROVIDER="offline")
with open(dest, "w", encoding="utf-8") as f:
    f.write("# Generated by scripts/deploy.sh — edit the source .env, then redeploy.\n")
    f.writelines(f"{k}={v}\n" for k, v in out.items())
PY
chmod 600 "$DEST/.env"

echo "==> python venv"
REQ_HASH="$(sha256sum "$DEST/backend/requirements.txt" | cut -d' ' -f1)"
if [ ! -x "$DEST/backend/.venv/bin/python" ]; then python3.11 -m venv "$DEST/backend/.venv"; fi
if [ "$(cat "$DEST/backend/.venv/.req_hash" 2>/dev/null)" != "$REQ_HASH" ]; then
  "$DEST/backend/.venv/bin/pip" install -q --upgrade pip
  "$DEST/backend/.venv/bin/pip" install -q -r "$DEST/backend/requirements.txt" "uvicorn[standard]"
  echo "$REQ_HASH" > "$DEST/backend/.venv/.req_hash"
fi

echo "==> migrate"
(cd "$DEST/backend" && .venv/bin/alembic upgrade head)

echo "==> restart api"
"$DEST/run.sh"

echo "==> smoke"
curl -sf "http://127.0.0.1:$PORT/api/health" && echo
curl -sf -o /dev/null -w "https://$DOMAIN -> %{http_code}\n" "https://$DOMAIN/" || echo "public URL not reachable yet (DNS/TLS?)"
